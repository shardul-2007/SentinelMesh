"""
Reproducible Synthetic Demonstration Dataset Generator for SENTINELMESH.

IMPORTANT DISCLOSURE:
All records generated by this module are SYNTHETIC DEMONSTRATION DATA designed
solely for testing, training walkthroughs, and hackathon demonstrations.
They do NOT represent captured production network traffic or real-world attacks.
"""

from datetime import datetime, timedelta
from pathlib import Path
from typing import Optional
import numpy as np
import pandas as pd

from src.utils import DEMO_CSV_PATH, setup_logger

logger = setup_logger("sentinelmesh.demo_data")


def generate_synthetic_demo_dataset(
    n_samples: int = 1200,
    seed: int = 42,
    save_path: Optional[Path] = DEMO_CSV_PATH,
) -> pd.DataFrame:
    """
    Generate a reproducible synthetic network flow dataset containing clearly
    labeled normal traffic and four representative suspicious traffic patterns:
      - BENIGN (~72%)
      - DDoS_Flood (~9%)
      - Port_Scan (~8%)
      - Brute_Force (~6%)
      - Data_Exfiltration (~5%)

    Includes subtle overlapping variance so supervised classifiers achieve
    realistic, non-trivial generalization metrics rather than synthetic 100% splits.
    """
    rng = np.random.default_rng(seed)

    n_benign = int(n_samples * 0.72)
    n_ddos = int(n_samples * 0.09)
    n_scan = int(n_samples * 0.08)
    n_brute = int(n_samples * 0.06)
    n_exfil = n_samples - (n_benign + n_ddos + n_scan + n_brute)

    base_time = datetime(2026, 11, 18, 8, 0, 0)
    internal_hosts = [f"10.0.1.{i}" for i in range(10, 65)]
    server_hosts = ["10.0.1.50", "10.0.1.51", "10.0.1.52", "10.0.1.60"]
    external_normal = [f"172.16.20.{i}" for i in range(5, 45)]

    rows = []

    def _add_flow(
        src_ip: str,
        dst_ip: str,
        src_port: int,
        dst_port: int,
        protocol: str,
        duration_ms: float,
        pkt_sent: int,
        pkt_recv: int,
        bytes_sent: int,
        bytes_recv: int,
        syn_count: int,
        failed_conns: int,
        label: str,
        offset_sec: int,
    ) -> None:
        duration_sec = max(duration_ms / 1000.0, 0.001)
        total_pkts = max(pkt_sent + pkt_recv, 1)
        total_bytes = max(bytes_sent + bytes_recv, 1)
        rows.append(
            {
                "timestamp": (base_time + timedelta(seconds=int(offset_sec))).isoformat(),
                "src_ip": src_ip,
                "dst_ip": dst_ip,
                "src_port": int(src_port),
                "dst_port": int(dst_port),
                "protocol": protocol,
                "flow_duration_ms": round(float(duration_ms), 2),
                "packets_sent": int(pkt_sent),
                "packets_recv": int(pkt_recv),
                "bytes_sent": int(bytes_sent),
                "bytes_recv": int(bytes_recv),
                "packet_rate": round(total_pkts / duration_sec, 2),
                "byte_rate": round(total_bytes / duration_sec, 2),
                "syn_flag_count": int(syn_count),
                "failed_conn_count": int(failed_conns),
                "avg_packet_size": round(total_bytes / total_pkts, 2),
                "is_synthetic_demo": True,
                "label": label,
            }
        )

    # 1. BENIGN traffic (HTTPS, HTTP, DNS, SSH maintenance, NTP)
    common_ports = [443, 443, 443, 80, 80, 53, 53, 22, 8080, 123]
    for _ in range(n_benign):
        dst_port = int(rng.choice(common_ports))
        proto = "UDP" if dst_port in (53, 123) else "TCP"
        duration = float(np.clip(rng.lognormal(mean=5.8, sigma=1.1), 15, 25000))
        pkt_sent = int(np.clip(rng.poisson(18) + rng.integers(2, 25), 2, 180))
        pkt_recv = int(np.clip(rng.poisson(22) + rng.integers(2, 30), 1, 220))
        bytes_sent = int(pkt_sent * rng.integers(90, 620))
        bytes_recv = int(pkt_recv * rng.integers(140, 1100))
        syn_count = int(rng.choice([0, 1, 1, 2])) if proto == "TCP" else 0
        failed_conns = int(rng.choice([0, 0, 0, 0, 1]))
        _add_flow(
            src_ip=str(rng.choice(internal_hosts)),
            dst_ip=str(rng.choice(external_normal + server_hosts)),
            src_port=int(rng.integers(32768, 60999)),
            dst_port=dst_port,
            protocol=proto,
            duration_ms=duration,
            pkt_sent=pkt_sent,
            pkt_recv=pkt_recv,
            bytes_sent=bytes_sent,
            bytes_recv=bytes_recv,
            syn_count=syn_count,
            failed_conns=failed_conns,
            label="BENIGN",
            offset_sec=int(rng.integers(0, 7200)),
        )

    # 2. DDoS_Flood (high packet rates, high SYN counts, targeting 10.0.1.50:443)
    botnet_ips = ["198.51.100.14", "198.51.100.19", "198.51.100.23", "203.0.113.88"]
    for _ in range(n_ddos):
        duration = float(np.clip(rng.uniform(40, 650), 20, 1500))
        pkt_sent = int(rng.integers(600, 3800))
        pkt_recv = int(rng.integers(0, 40))
        bytes_sent = int(pkt_sent * rng.integers(54, 140))
        bytes_recv = int(pkt_recv * rng.integers(40, 90))
        syn_count = int(rng.integers(250, 1800))
        failed_conns = int(rng.integers(10, 85))
        _add_flow(
            src_ip=str(rng.choice(botnet_ips)),
            dst_ip="10.0.1.50",
            src_port=int(rng.integers(1024, 65535)),
            dst_port=int(rng.choice([443, 80])),
            protocol=str(rng.choice(["TCP", "TCP", "UDP"])),
            duration_ms=duration,
            pkt_sent=pkt_sent,
            pkt_recv=pkt_recv,
            bytes_sent=bytes_sent,
            bytes_recv=bytes_recv,
            syn_count=syn_count,
            failed_conns=failed_conns,
            label="DDoS_Flood",
            offset_sec=int(rng.integers(1800, 2700)),
        )

    # 3. Port_Scan (probing many sensitive ports with small packets & failed connections)
    scan_ports = [21, 22, 23, 25, 80, 135, 139, 445, 1433, 3306, 3389, 5900, 6379, 8080]
    scanner_ips = ["198.51.100.77", "198.51.100.78"]
    for _ in range(n_scan):
        duration = float(np.clip(rng.uniform(5, 180), 3, 400))
        pkt_sent = int(rng.integers(1, 6))
        pkt_recv = int(rng.integers(0, 2))
        bytes_sent = int(pkt_sent * rng.integers(40, 74))
        bytes_recv = int(pkt_recv * rng.integers(40, 64))
        syn_count = int(rng.integers(3, 18))
        failed_conns = int(rng.integers(8, 45))
        _add_flow(
            src_ip=str(rng.choice(scanner_ips)),
            dst_ip=str(rng.choice(server_hosts)),
            src_port=int(rng.integers(40000, 65000)),
            dst_port=int(rng.choice(scan_ports)),
            protocol="TCP",
            duration_ms=duration,
            pkt_sent=pkt_sent,
            pkt_recv=pkt_recv,
            bytes_sent=bytes_sent,
            bytes_recv=bytes_recv,
            syn_count=syn_count,
            failed_conns=failed_conns,
            label="Port_Scan",
            offset_sec=int(rng.integers(3000, 3900)),
        )

    # 4. Brute_Force (repeated auth failures on SSH/RDP/MySQL)
    brute_ips = ["203.0.113.45", "203.0.113.46"]
    for _ in range(n_brute):
        duration = float(np.clip(rng.uniform(120, 2400), 60, 4000))
        pkt_sent = int(rng.integers(18, 95))
        pkt_recv = int(rng.integers(15, 80))
        bytes_sent = int(pkt_sent * rng.integers(110, 260))
        bytes_recv = int(pkt_recv * rng.integers(90, 210))
        syn_count = int(rng.integers(8, 35))
        failed_conns = int(rng.integers(25, 140))
        _add_flow(
            src_ip=str(rng.choice(brute_ips)),
            dst_ip=str(rng.choice(["10.0.1.51", "10.0.1.52"])),
            src_port=int(rng.integers(35000, 62000)),
            dst_port=int(rng.choice([22, 3389, 3306])),
            protocol="TCP",
            duration_ms=duration,
            pkt_sent=pkt_sent,
            pkt_recv=pkt_recv,
            bytes_sent=bytes_sent,
            bytes_recv=bytes_recv,
            syn_count=syn_count,
            failed_conns=failed_conns,
            label="Brute_Force",
            offset_sec=int(rng.integers(4200, 5200)),
        )

    # 5. Data_Exfiltration (massive outbound bytes to suspicious port/external IP)
    exfil_sources = ["10.0.1.24", "10.0.1.31"]
    for _ in range(n_exfil):
        duration = float(np.clip(rng.uniform(3500, 28000), 1000, 45000))
        pkt_sent = int(rng.integers(900, 4500))
        pkt_recv = int(rng.integers(15, 90))
        bytes_sent = int(pkt_sent * rng.integers(1150, 1480))
        bytes_recv = int(pkt_recv * rng.integers(60, 150))
        syn_count = int(rng.integers(1, 4))
        failed_conns = int(rng.integers(0, 3))
        _add_flow(
            src_ip=str(rng.choice(exfil_sources)),
            dst_ip="192.0.2.99",
            src_port=int(rng.integers(42000, 61000)),
            dst_port=int(rng.choice([4444, 8443, 9001])),
            protocol="TCP",
            duration_ms=duration,
            pkt_sent=pkt_sent,
            pkt_recv=pkt_recv,
            bytes_sent=bytes_sent,
            bytes_recv=bytes_recv,
            syn_count=syn_count,
            failed_conns=failed_conns,
            label="Data_Exfiltration",
            offset_sec=int(rng.integers(5400, 6600)),
        )

    df = pd.DataFrame(rows)
    # Shuffle deterministically and assign sequential record IDs
    df = df.sample(frac=1.0, random_state=seed).reset_index(drop=True)
    df.insert(0, "record_id", [f"FLOW-{i + 1:05d}" for i in range(len(df))])

    if save_path is not None:
        save_path.parent.mkdir(parents=True, exist_ok=True)
        df.to_csv(save_path, index=False)
        logger.info("Generated synthetic demo dataset (%d rows) at %s", len(df), save_path)

    return df


def load_or_create_demo_dataset() -> pd.DataFrame:
    """Load the synthetic demonstration CSV, creating it deterministically if missing."""
    if not DEMO_CSV_PATH.exists():
        return generate_synthetic_demo_dataset(save_path=DEMO_CSV_PATH)
    return pd.read_csv(DEMO_CSV_PATH)
